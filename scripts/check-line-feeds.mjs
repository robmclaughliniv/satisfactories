import assert from 'node:assert/strict';
import { createServer } from 'vite';
const server = await createServer({ server: { middlewareMode:true,hmr:false,ws:false }, appType:'custom' });
try {
  const { FactorySchema, WorldSchema, SCHEMA_VERSION } = await server.ssrLoadModule('/src/model/schema.ts');
  const { computeFactoryLineFeeds, computeWorldLineFeeds, outputRemaining, nextLineName } = await server.ssrLoadModule('/src/state/lineFeeds.ts');
  const { importedByItem, allocationShipments } = await server.ssrLoadModule('/src/model/logistics.ts');
  const { aggregateEffective, itemExported } = await server.ssrLoadModule('/src/state/derive.ts');
  const { buildFlows } = await server.ssrLoadModule('/src/state/flows.ts');
  const { buildMapConnections } = await server.ssrLoadModule('/src/model/mapConnections.ts');
  const { migratePersisted } = await server.ssrLoadModule('/src/model/migrations.ts');
  const { captureBaseline, applyBaseline, parseBaseline, isFactoryDirty } = await server.ssrLoadModule('/src/model/baseline.ts');
  const { buildBackupEnvelope } = await server.ssrLoadModule('/src/model/backup.ts');
  const { SAMPLE_WORLD } = await server.ssrLoadModule('/src/data/templates.ts');
  const { instantiateTemplate } = await server.ssrLoadModule('/src/model/world.ts');
  const factory=(id,sections=[],localInputs=[]) => FactorySchema.parse({id,name:id,color:'#F5882E',status:'planned',tier:'Mini-factory',tagline:'',tags:[],cover:'',x:0,y:0,sections,localInputs,baseline:''});
  const row=(id,recipeId,count=1) => ({id,name:id,recipeId,count,allocations:[],destinations:[],sources:[]});
  const smelt=row('Iron Ingot 1','iron_ingot',4);
  const plate=row('Iron Plate 1','iron_plate',2);
  const plate2=row('Iron Plate 2','iron_plate',1);
  const a=factory('A',[{id:'floor1',name:'First floor',rows:[smelt,plate,plate2]}],[{id:'ore',item:'Iron Ore',rate:120,t:'Belt'}]);
  // Use parsed objects so defaults are always exercised.
  const [source,target,target2]=a.sections[0].rows;
  source.sources=[{kind:'local',localInputId:'ore',rate:120}];
  const remote=row('Remote Plates','iron_plate',1);
  remote.sources=[{kind:'import',item:'Iron Ingot',rate:30}];
  const b=factory('B',[{id:'other-floor',name:'Other floor',rows:[remote]}]);
  const world=WorldSchema.parse({id:'w',name:'Test',factories:[],routes:[],stations:[],createdAt:'',updatedAt:''});
  world.factories=[a,b];
  const feed=() => computeFactoryLineFeeds(world,a);
  assert.equal(feed().byRowId[source.id].effectiveOutputs[0].rate,120);
  assert.equal(outputRemaining(feed(),source,'Iron Ingot'),120);
  assert.equal(itemExported(world,a,'Iron Ingot'),0);
  assert.equal(nextLineName(a,'iron_plate'),'Iron Plate 3');
  source.allocations=[{id:'feed1',kind:'line',targetId:target.id,item:'Iron Ingot',rate:40}];
  assert.equal(outputRemaining(feed(),source,'Iron Ingot'),80);
  assert.equal(feed().byRowId[target.id].inputs[0].available,40);
  source.allocations[0].rate=60;
  source.allocations.push({id:'feed2',kind:'line',targetId:target2.id,item:'Iron Ingot',rate:20});
  source.allocations.push({id:'export',kind:'factory',targetId:b.id,item:'Iron Ingot',rate:30});
  assert.equal(outputRemaining(feed(),source,'Iron Ingot'),10);
  assert.equal(feed().delivered.feed1,60);
  assert.equal(feed().delivered.feed2,20);
  assert.equal(importedByItem(world,b,'Iron Ingot'),30);
  assert.equal(computeFactoryLineFeeds(world,b).byRowId[remote.id].efficiency,1);
  assert.equal(itemExported(world,a,'Iron Ingot'),30);
  assert.equal(aggregateEffective(world,b).per['Iron Plate'].out,20);
  assert.equal(buildFlows(world,a).find(f => f.dir==='export').total,30);
  assert.equal(buildFlows(world,b).find(f => f.dir==='import').total,30);
  assert.equal(buildMapConnections(world)[0].items[0].rate,30);
  world.routes=[{id:'existing-transport',from:'A',to:'B',item:'Iron Ingot',rate:30,t:'Belt'}];
  assert.equal(importedByItem(world,b,'Iron Ingot'),30,'Transport must not duplicate allocation delivery');
  assert.equal(itemExported(world,a,'Iron Ingot'),30);
  assert.equal(buildMapConnections(world)[0].items.length,1);
  // Falling production retains every request, holds affected shipments, and reports the deficit.
  a.localInputs[0].rate=80;source.sources[0].rate=80;
  assert.equal(outputRemaining(feed(),source,'Iron Ingot'),-30);
  assert.equal(feed().delivered.feed1,0);
  assert.equal(feed().delivered.export,0);
  assert.equal(source.allocations[0].rate,60);
  assert.equal(importedByItem(world,b,'Iron Ingot'),0);
  source.allocations[1].rate=10;source.allocations[2].rate=10;
  assert.equal(feed().delivered.feed1,60);
  assert.equal(feed().delivered.export,10);
  assert.equal(importedByItem(world,b,'Iron Ingot'),10);
  assert.equal(computeFactoryLineFeeds(world,b).byRowId[remote.id].efficiency,0,'Oversubscribed input pool is held');
  b.sections[0].rows[0].sources[0].rate=10;
  assert.equal(computeFactoryLineFeeds(world,b).byRowId[remote.id].efficiency,1/3);
  // Moving categories preserves line IDs and incoming connections.
  a.sections.push({id:'floor2',name:'Second floor',rows:[a.sections[0].rows.pop()]});
  assert.equal(feed().delivered.feed2,10);
  assert.equal(feed().byRowId[target2.id].inputs[0].available,10);
  // Commit/reset includes names, categories, rates and factory shipments.
  a.baseline=captureBaseline(a,world.routes,world.stations);
  assert.equal(isFactoryDirty(a,world.routes,world.stations),false);
  const committed=parseBaseline(a.baseline);
  source.name='Changed';source.allocations[0].rate=1;
  assert.equal(isFactoryDirty(a,world.routes,world.stations),true);
  applyBaseline(a,world,committed);
  assert.equal(a.sections[0].rows[0].name,'Iron Ingot 1');
  assert.equal(a.sections[0].rows[0].allocations[0].rate,60);
  assert.equal(isFactoryDirty(a,world.routes,world.stations),false);
  const backup=buildBackupEnvelope({worlds:[world],worldId:'w',favItems:[],favFactories:[]});
  assert.equal(migratePersisted(JSON.parse(JSON.stringify(backup))).schemaVersion,SCHEMA_VERSION);
  // v9 migration preserves IDs, names categories, converts feeds and snapshots.
  const legacy=JSON.parse(JSON.stringify(backup));legacy.schemaVersion=9;
  legacy.worlds[0].factories[0].sections[0].rows[0].destinations=[{kind:'section',sectionId:'floor2'},{kind:'export'}];
  legacy.worlds[0].factories[0].sections[0].rows[0].allocations=[];
  legacy.worlds[0].factories.forEach(f => f.sections.forEach(s => s.rows.forEach(r => {delete r.name;r.sources.forEach(s => delete s.rate);})));
  const migrated=migratePersisted(legacy);
  assert.ok(migrated);
  const upgraded=migrated.worlds[0].factories[0].sections[0].rows[0];
  assert.equal(upgraded.id,'Iron Ingot 1');
  assert.equal(upgraded.name,'Iron Ingot 1');
  assert.ok(upgraded.allocations.some(a => a.kind==='line' && a.targetId===target2.id));
  assert.ok(upgraded.allocations.some(a => a.kind==='review'));
  assert.ok(upgraded.allocations.some(a => a.kind==='factory' && a.targetId==='B' && a.rate===30));
  assert.equal(upgraded.sources[0].rate,80);
  const sample=instantiateTemplate(SAMPLE_WORLD);
  assert.ok(sample.factories.every(f => f.sections.every(s => s.rows.every(r => !!r.name))));
  assert.ok(sample.factories.every(f => !isFactoryDirty(f,sample.routes,sample.stations)));
  assert.ok(Object.values(computeWorldLineFeeds(sample)).every(f => f.converged));
  assert.ok(allocationShipments(world).every(s => Number.isFinite(s.rate)));
  // Byproducts have independent budgets; an unseeded recycling loop creates no supply.
  const fuel = row('Fuel 1','fuel');
  fuel.sources=[{kind:'local',localInputId:'oil',rate:60}];
  fuel.allocations=[{id:'fuel-export',kind:'factory',targetId:'B',item:'Fuel',rate:20}, {id:'resin-export',kind:'factory',targetId:'B',item:'Polymer Resin',rate:10}];
  const refinery=factory('Refinery',[{id:'ref',name:'Refining',rows:[fuel]}],[{id:'oil',item:'Oil',rate:60,t:'Pipe'}]);
  world.factories.push(refinery);
  const refineryFeed=computeFactoryLineFeeds(world,refinery);
  assert.equal(outputRemaining(refineryFeed,refinery.sections[0].rows[0],'Fuel'),20);
  assert.equal(outputRemaining(refineryFeed,refinery.sections[0].rows[0],'Polymer Resin'),20);
  const plastic=row('Plastic loop','alt_recycled_plastic');
  const rubber=row('Rubber loop','alt_recycled_rubber');
  plastic.allocations=[{id:'plastic-loop',kind:'line',targetId:rubber.id,item:'Plastic',rate:30}];
  rubber.allocations=[{id:'rubber-loop',kind:'line',targetId:plastic.id,item:'Rubber',rate:30}];
  const loop=factory('Loop',[{id:'loop',name:'Loop',rows:[plastic,rubber]}]);world.factories.push(loop);
  const loopFeed=computeFactoryLineFeeds(world,loop);
  assert.equal(loopFeed.byRowId[plastic.id].efficiency,0);
  assert.equal(loopFeed.byRowId[rubber.id].efficiency,0);
  assert.equal(loopFeed.converged,true);

  const { assignInputSupply, availableInputSupply } = await server.ssrLoadModule('/src/state/inputSupply.ts');
  const inputFactory = factory('Input factory',[{id:'inputs',name:'Inputs',rows:[row('Input 1','iron_ingot',4),row('Input 2','iron_ingot',4)]}],[{id:'shared-ore',item:'Iron Ore',rate:240,t:'Belt'}]);
  world.factories.push(inputFactory);
  const [input1,input2]=inputFactory.sections[0].rows;
  const claim={kind:'local',item:'Iron Ore',localInputId:'shared-ore',rate:120};
  assert.equal(assignInputSupply(world,inputFactory.id,input1.id,claim),null);
  assert.equal(availableInputSupply(world,inputFactory,input2.id,claim),120);
  assert.ok(assignInputSupply(world,inputFactory.id,input2.id,{...claim,rate:121}));
  assert.equal(assignInputSupply(world,inputFactory.id,input2.id,claim),null);
  assert.equal(inputFactory.localInputs.length,1,'Two lines share one factory-owned node');
  assert.equal(availableInputSupply(world,inputFactory,input2.id,claim),0);
  assert.equal(computeFactoryLineFeeds(world,inputFactory).byRowId[input1.id].efficiency,1);
  assert.equal(computeFactoryLineFeeds(world,inputFactory).byRowId[input2.id].efficiency,1);
  assert.equal(assignInputSupply(world,inputFactory.id,input1.id,{...claim,rate:60,previousKey:'local:shared-ore'}),null);
  assert.equal(availableInputSupply(world,inputFactory,input2.id,claim),60);
  input1.sources=[];
  assert.equal(inputFactory.localInputs[0].rate,240,'Releasing a claim preserves the factory node');
  assert.equal(availableInputSupply(world,inputFactory,input1.id,claim),120);
  assert.ok(assignInputSupply(world,inputFactory.id,input1.id,{...claim,item:'Screws'}));
  assert.ok(assignInputSupply(world,inputFactory.id,input1.id,{...claim,rate:-10}));
  assert.ok(assignInputSupply(world,inputFactory.id,input1.id,{...claim,localInputId:'missing'}));
  assert.ok(assignInputSupply(world,inputFactory.id,input1.id,{kind:'import',item:'Iron Ore',rate:120}));
  const receiving=b.sections[0].rows[0];
  assert.equal(assignInputSupply(world,b.id,receiving.id,{kind:'import',item:'Iron Ingot',rate:4,previousKey:'import:Iron Ingot'}),null);
  b.sections[0].rows.push(row('Second imported line','iron_plate',1));
  assert.equal(availableInputSupply(world,b,'Second imported line',{kind:'import',item:'Iron Ingot',rate:6}),6);
  assert.equal(assignInputSupply(world,b.id,'Second imported line',{kind:'import',item:'Iron Ingot',rate:6}),null);
  assert.ok(assignInputSupply(world,b.id,'Second imported line',{kind:'import',item:'Iron Ingot',rate:7,previousKey:'import:Iron Ingot'}));
  console.log('Passed: shared factory nodes and imports, exact claims, overclaim prevention, editing and releasing claims without deleting supply.');
  console.log('Passed: exact line allocations, remaining budgets, same-category feeds, cross-factory deliveries, shortage holds, transport deduplication, category moves, names, migration, templates, commit/reset and backup round trips.');
} finally { await server.close(); }
